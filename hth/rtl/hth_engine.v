`timescale 1ns/1ns
////////////////////////////////////////////////////////////////////////
// hth_engine : FAST-LIO measurement-model accumulator (see ../SPEC.md)
//
// Reads 32-bit words from the receive FIFO (BEGIN / POINTS / END packets),
// runs a 54-instruction multiply-accumulate program per point on ONE 32x32
// multiplier, keeps 27 exact 80-bit sums (21 of H^T H + 6 of H^T h) and, on
// END, writes an 85-word reply into the transmit buffer and toggles
// result_tgl so the 25 MHz Ethernet side sends it.
//
// Clock: 50 MHz (RMII reference clock). Everything here is one clock domain.
////////////////////////////////////////////////////////////////////////
module hth_engine
(
    input   wire            clk         ,   // 50 MHz
    input   wire            rst_n       ,
    // receive FIFO (Altera dcfifo, lpm_showahead = OFF: q is valid 1 clock after rdreq)
    input   wire    [31:0]  fifo_q      ,
    input   wire            fifo_empty  ,
    output  wire            fifo_rdreq  ,
    input   wire            fifo_ovf    ,   // sticky "a write was refused because FIFO was full" (already synchronised)
    input   wire    [31:0]  diag        ,   // receive counters from the Ethernet side, reported in reply word 3
    // transmit buffer write port
    output  reg             tx_we       ,
    output  reg     [6:0]   tx_addr     ,
    output  reg     [31:0]  tx_wdata    ,
    output  reg             result_tgl      // toggles once per finished reply
);

`include "hth_ucode.vh"     // localparam NUOPS + function ucode(pc), generated by model/hth_model.py

localparam  LAT         = 3;            // issue -> multiply -> accumulate/write-back
localparam  ONE_Q30     = 32'h4000_0000;
localparam  NSUM        = 27;
localparam  NREPLY      = 7'd85;        // 4 status words + 27 x 3 words

localparam  S_HDR       = 3'd0,         // wait for a packet header word
            S_CONST     = 3'd1,         // BEGIN: 21 constant words
            S_LOAD      = 3'd2,         // POINTS: 7 words of one point
            S_RUN       = 3'd3,         // issue the 54 instructions
            S_DRAIN     = 3'd4,         // let the last instructions leave the pipeline
            S_OUT       = 3'd5,         // END: write the reply into the transmit buffer
            S_FIN       = 3'd6;         // one clock later: announce the reply (all words are in the RAM by then)

localparam  M_NOP = 3'd0, M_ACC_START = 3'd1, M_ACC_ADD = 3'd2, M_ACC_SUB = 3'd3,
            M_SUM_ADD = 3'd4, M_SUM_SUB = 3'd5;

reg     [2:0]   state;
reg     [4:0]   widx;           // word index inside BEGIN / point
reg     [15:0]  pts_left;
reg     [15:0]  iter_id;
reg     [31:0]  point_count;
reg     [15:0]  bad_hdr_cnt;
reg     [6:0]   pc;             // instruction counter
reg     [2:0]   drain;
reg     [6:0]   oidx;           // reply word index
reg     [4:0]   ok;             // sum index while writing the reply
reg     [1:0]   opart;          // 0,1,2 = high, middle, low word of a sum

//---------------------------------------------------------------- FIFO reading
// One word every 2 clocks: rdreq in clock t, word valid in clock t+1.
wire            want_word = (state == S_HDR) || (state == S_CONST) || (state == S_LOAD);
reg             rd_pending;
assign  fifo_rdreq = want_word && !fifo_empty && !rd_pending;
wire            word_valid = rd_pending;

always @(posedge clk or negedge rst_n)
    if (!rst_n) rd_pending <= 1'b0;
    else        rd_pending <= fifo_rdreq;

//---------------------------------------------------------------- register file
// 0-8 R | 9-17 R_LI | 18-20 t_LI | 21-23 pb | 24-26 n | 27 pd2 | 28-30 p | 31-33 C | 34-36 A | 37 = 1.0 (Q2.30)
reg     [31:0]  rf [0:36];

function [31:0] rf_read;
    input [5:0] idx;
    rf_read = (idx == 6'd37) ? ONE_Q30 : rf[idx];
endfunction

//---------------------------------------------------------------- pipeline
// stage 1: issue  -> read the two operands
wire    [21:0]  uop = ucode(pc);
reg             s1_valid, s1_wb;
reg     [2:0]   s1_mode;
reg     [5:0]   s1_dst;
reg     [31:0]  s1_a, s1_b;
// stage 2: multiply
reg             s2_valid, s2_wb;
reg     [2:0]   s2_mode;
reg     [5:0]   s2_dst;
reg signed [63:0] s2_prod;
// stage 3: accumulate / write back
reg signed [63:0] acc;
reg signed [63:0] acc_next;

always @(posedge clk or negedge rst_n)
    if (!rst_n) begin
        s1_valid <= 1'b0; s1_wb <= 1'b0; s1_mode <= M_NOP; s1_dst <= 6'd0; s1_a <= 32'd0; s1_b <= 32'd0;
    end else begin
        s1_valid <= (state == S_RUN);
        s1_wb    <= uop[21];
        s1_mode  <= (state == S_RUN) ? uop[20:18] : M_NOP;
        s1_dst   <= uop[17:12];
        s1_a     <= rf_read(uop[11:6]);
        s1_b     <= rf_read(uop[5:0]);
    end

always @(posedge clk or negedge rst_n)
    if (!rst_n) begin
        s2_valid <= 1'b0; s2_wb <= 1'b0; s2_mode <= M_NOP; s2_dst <= 6'd0; s2_prod <= 64'sd0;
    end else begin
        s2_valid <= s1_valid;
        s2_wb    <= s1_wb;
        s2_mode  <= s1_mode;
        s2_dst   <= s1_dst;
        s2_prod  <= $signed(s1_a) * $signed(s1_b);
    end

always @(*)
    case (s2_mode)
        M_ACC_START: acc_next = s2_prod;
        M_ACC_ADD:   acc_next = acc + s2_prod;
        M_ACC_SUB:   acc_next = acc - s2_prod;
        default:     acc_next = acc;
    endcase

wire signed [79:0] prod80 = {{16{s2_prod[63]}}, s2_prod};

//---------------------------------------------------------------- the 27 sums live in an M9K RAM (32 x 80 bit)
// Read-modify-write: the address of an instruction is known one stage early (s1_dst), so the RAM read happens
// in the multiply stage and the new value is written in stage 3. Two instructions never touch the same sum within
// 2 clocks (checked by the microcode generator). sum_valid lets BEGIN clear all 27 sums in one clock.
// (2026-11-10: was 27 x 80-bit registers with their own adders -> 97 % of the logic elements)
reg     [79:0]  sum_mem [0:31];
reg     [79:0]  sum_rd;
reg     [26:0]  sum_valid;
wire    [4:0]   sum_raddr = (state == S_OUT) ? ok : s1_dst[4:0];
wire            sum_we    = (s2_mode == M_SUM_ADD) || (s2_mode == M_SUM_SUB);
wire signed [79:0] sum_old = sum_valid[s2_dst[4:0]] ? $signed(sum_rd) : 80'sd0;
wire    [79:0]  sum_wd    = (s2_mode == M_SUM_ADD) ? sum_old + prod80 : sum_old - prod80;
wire    [79:0]  sum_out   = sum_valid[ok] ? sum_rd : 80'd0;      // value used while writing the reply

always @(posedge clk) begin
    if (sum_we) sum_mem[s2_dst[4:0]] <= sum_wd;
    sum_rd <= sum_mem[sum_raddr];
end

//---------------------------------------------------------------- main state machine + register file + sums
always @(posedge clk or negedge rst_n)
    if (!rst_n) begin
        state <= S_HDR; widx <= 5'd0; pts_left <= 16'd0; iter_id <= 16'd0; point_count <= 32'd0;
        bad_hdr_cnt <= 16'd0; pc <= 7'd0; drain <= 3'd0; oidx <= 7'd0; ok <= 5'd0; opart <= 2'd0;
        acc <= 64'sd0; tx_we <= 1'b0; tx_addr <= 7'd0; tx_wdata <= 32'd0; result_tgl <= 1'b0;
        sum_valid <= 27'd0;
    end else begin
        tx_we <= 1'b0;

        // ---- stage 3 of the pipeline (runs in every state) ----
        acc <= acc_next;
        if ((s2_mode == M_ACC_START || s2_mode == M_ACC_ADD || s2_mode == M_ACC_SUB) && s2_wb)
            rf[s2_dst] <= acc_next[61:30];                  // (acc >>> 30), low 32 bits
        if (sum_we) sum_valid[s2_dst[4:0]] <= 1'b1;

        case (state)
        S_HDR:
            if (word_valid) begin
                if (fifo_q[31:24] != 8'hA5)
                    bad_hdr_cnt <= bad_hdr_cnt + 16'd1;     // not a header: skip this word (resynchronise)
                else case (fifo_q[23:16])
                    8'h01: begin iter_id <= fifo_q[15:0]; widx <= 5'd0; state <= S_CONST; end
                    8'h02: if (fifo_q[15:0] != 16'd0) begin pts_left <= fifo_q[15:0]; widx <= 5'd0; state <= S_LOAD; end
                    8'h03: begin oidx <= 7'd0; ok <= 5'd0; opart <= 2'd0; state <= S_OUT; end
                    default: bad_hdr_cnt <= bad_hdr_cnt + 16'd1;
                endcase
            end
        S_CONST:
            if (word_valid) begin
                rf[widx] <= fifo_q;                         // R, R_LI, t_LI -> rf[0..20]
                widx <= widx + 5'd1;
                if (widx == 5'd20) begin
                    sum_valid <= 27'd0;
                    point_count <= 32'd0;
                    bad_hdr_cnt <= 16'd0;
                    state <= S_HDR;
                end
            end
        S_LOAD:
            if (word_valid) begin
                rf[5'd21 + widx] <= fifo_q;                 // pb, n, pd2 -> rf[21..27]
                widx <= widx + 5'd1;
                if (widx == 5'd6) begin pc <= 7'd0; state <= S_RUN; end
            end
        S_RUN: begin
            pc <= pc + 7'd1;
            if (pc == NUOPS - 1) begin drain <= LAT; state <= S_DRAIN; end
        end
        S_DRAIN: begin
            drain <= drain - 3'd1;
            if (drain == 3'd1) begin
                point_count <= point_count + 32'd1;
                pts_left <= pts_left - 16'd1;
                widx <= 5'd0;
                state <= (pts_left == 16'd1) ? S_HDR : S_LOAD;
            end
        end
        S_OUT:
            if (oidx < 7'd4) begin                          // 4 status words
                tx_we <= 1'b1; tx_addr <= oidx; oidx <= oidx + 7'd1;
                case (oidx[1:0])
                    2'd0: tx_wdata <= {8'hA5, 8'h03, iter_id};
                    2'd1: tx_wdata <= point_count;
                    2'd2: tx_wdata <= {bad_hdr_cnt, 15'd0, fifo_ovf};
                    default: tx_wdata <= diag;              // {2'b0, frames started, SFD ok, accepted} mod 1024
                endcase
            end else begin                                  // 27 sums, 4 clocks each: wait for RAM, high, middle, low
                if (opart != 2'd0) begin
                    tx_we <= 1'b1; tx_addr <= oidx; oidx <= oidx + 7'd1;
                    case (opart)
                        2'd1: tx_wdata <= {{16{sum_out[79]}}, sum_out[79:64]};
                        2'd2: tx_wdata <= sum_out[63:32];
                        default: tx_wdata <= sum_out[31:0];
                    endcase
                end
                opart <= opart + 2'd1;
                if (opart == 2'd3) begin
                    ok <= ok + 5'd1;
                    if (ok == NSUM - 1) state <= S_FIN;
                end
            end
        S_FIN: begin
            result_tgl <= ~result_tgl;
            state <= S_HDR;
        end
        default: state <= S_HDR;
        endcase
    end

endmodule
